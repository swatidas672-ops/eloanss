/** Cities available in a state, with the district's own name first when it is one. */
export const citiesOf = (state: string, district?: string): string[] => {
  const list = citiesByState[state] ?? [];
  if (!district) return list;
  const match = list.find((c) => c.toLowerCase() === district.toLowerCase());
  return match ? [match, ...list.filter((c) => c !== match)] : [district, ...list];
};
